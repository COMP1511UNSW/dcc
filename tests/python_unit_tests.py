class CReprTests(unittest.TestCase):
    """c_repr turns a Python string into a C string literal for the embedded C code"""

    def test_plain(self):
        self.assertEqual(dcc_compile.c_repr("abc"), '"abc"')

    def test_escapes(self):
        self.assertEqual(dcc_compile.c_repr('a"b\\c?'), r'"a\"b\\c\?"')

    def test_control_and_non_ascii_characters(self):
        # octal escapes are used because a digit can safely follow them
        self.assertEqual(dcc_compile.c_repr("x\n\té1"), r'"x\012\011\303\2511"')

    def test_undecodable_filesystem_bytes(self):
        # Python represents undecodable bytes in paths and argv as lone surrogates
        self.assertEqual(dcc_compile.c_repr(os.fsdecode(b"\xff")), r'"\377"')

    @unittest.skipUnless(shutil.which("clang"), "clang not available")
    def test_round_trip_through_clang(self):
        strings = [
            "plain",
            'q"uote',
            "back\\slash",
            "tri??=graph",
            "new\nline",
            "café \U0001f600",
            "é123",
        ]
        source = "#include <stdio.h>\nint main(void) {\n"
        for s in strings:
            source += f"    fputs({dcc_compile.c_repr(s)}, stdout); putchar(0);\n"
        source += "    return 0;\n}\n"
        with tempfile.TemporaryDirectory() as d:
            executable = os.path.join(d, "a.out")
            command = ["clang", "-Wall", "-Wextra", "-Wtrigraphs", "-Werror", "-x", "c", "-", "-o", executable]
            p = subprocess.run(command, input=source, text=True, capture_output=True, check=False)
            self.assertEqual(p.returncode, 0, p.stderr)
            output = subprocess.run([executable], capture_output=True, check=True).stdout
        self.assertEqual(output.split(b"\0")[:-1], [s.encode("utf-8") for s in strings])


class EmbeddingTests(unittest.TestCase):
    """helpers used to embed files and the second executable in the compiled program"""

    def test_the_object_cache_key_ignores_where_the_object_is_written(self):
        # the object goes to a new temporary directory on every compilation,
        # so including its pathname would mean the cache never hit
        command = ["clang", "-c", "-x", "c", "-", "-o", "/tmp/one/w.o", "-O3"]
        self.assertEqual(
            dcc_compile.command_without_output_pathname(command),
            ["clang", "-c", "-x", "c", "-", "-O3"],
        )

    def test_the_object_cache_key_follows_what_was_compiled(self):
        fake_options = types.SimpleNamespace(
            clang_version="19.1.7", debug=0, debug_print=lambda *a, **k: None
        )
        command = ["clang", "-c", "-", "-o", "/tmp/a/w.o", "-O3"]
        key = dcc_compile.wrapper_object_cache_pathname(fake_options, "source", command)
        self.assertIsNotNone(key)
        # the same compilation in a different temporary directory is the same
        elsewhere = ["clang", "-c", "-", "-o", "/tmp/b/w.o", "-O3"]
        self.assertEqual(
            key, dcc_compile.wrapper_object_cache_pathname(fake_options, "source", elsewhere)
        )
        # a different source, option or compiler version is not
        for other in [
            dcc_compile.wrapper_object_cache_pathname(fake_options, "other", command),
            dcc_compile.wrapper_object_cache_pathname(
                fake_options, "source", ["clang", "-c", "-", "-o", "/tmp/a/w.o", "-O0"]
            ),
        ]:
            self.assertNotEqual(key, other)
        fake_options.clang_version = "18.1.0"
        self.assertNotEqual(
            key, dcc_compile.wrapper_object_cache_pathname(fake_options, "source", command)
        )

    def test_the_object_cache_can_be_turned_off(self):
        fake_options = types.SimpleNamespace(
            clang_version="19.1.7", debug=0, debug_print=lambda *a, **k: None
        )
        with mock.patch.dict(os.environ, {"DCC_NO_WRAPPER_CACHE": "1"}):
            self.assertIsNone(
                dcc_compile.wrapper_object_cache_pathname(fake_options, "s", ["clang", "-c"])
            )

    def test_minify_removes_only_comment_lines(self):
        source = b"# comment\nx = 1  # trailing comment kept\n    # indented comment\ny = '#'\n"
        self.assertEqual(dcc_compile.minify(source), b"x = 1  # trailing comment kept\ny = '#'\n")

    def test_linker_reports_missing_main(self):
        gnu_ld = "/usr/bin/ld: x.o: in function `_start':\n(.text+0x1b): undefined reference to `main'\n"
        lld = "ld.lld: error: undefined symbol: main\n>>> referenced by crt1.o\n"
        self.assertTrue(dcc_compile.linker_reports_missing_main(gnu_ld))
        self.assertTrue(dcc_compile.linker_reports_missing_main(lld))
        self.assertFalse(dcc_compile.linker_reports_missing_main("x.c:(.text+0x10): undefined reference to `main_menu'"))
        self.assertFalse(dcc_compile.linker_reports_missing_main("ld.lld: error: undefined symbol: mainloop\n"))

    def test_linker_reports_renamed_function(self):
        c = "/usr/bin/ld: x.o: undefined reference to `__renamed_read'\n"
        lld = "ld.lld: error: undefined symbol: __renamed_read\n"
        # ld demangles C++, so the renamed name is not alone after the backtick
        demangled = "/usr/bin/ld: x.o: undefined reference to `std::istream::__renamed_read(char*, long)'\n"
        template = "/usr/bin/ld: undefined reference to `std::basic_istream<char, std::char_traits<char> >::__renamed_read(char*, long)'\n"
        lld_demangled = "ld.lld: error: undefined symbol: std::basic_ostream<char, std::char_traits<char> >::__renamed_write(char const*, long)\n"
        self.assertTrue(dcc_compile.linker_reports_renamed_function(c))
        self.assertTrue(dcc_compile.linker_reports_renamed_function(lld))
        self.assertTrue(dcc_compile.linker_reports_renamed_function(demangled))
        self.assertTrue(dcc_compile.linker_reports_renamed_function(template))
        self.assertTrue(dcc_compile.linker_reports_renamed_function(lld_demangled))
        self.assertFalse(dcc_compile.linker_reports_renamed_function("undefined reference to `read'\n"))
        self.assertFalse(dcc_compile.linker_reports_renamed_function("__renamed_read is fine\n"))


