class SourceLineTests(unittest.TestCase):
    """fileline and Location.surrounding_source show the source around an error"""

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.filename = os.path.join(self.temp_dir.name, "prog.c")
        self.write_source("int main(void) {\n    int a[10] = {0};\n    return a[10];\n}\n")

    def tearDown(self):
        self.temp_dir.cleanup()

    def write_source(self, source):
        with open(self.filename, "w", encoding="utf-8") as f:
            f.write(source)
        util.cached_source_files.clear()

    def test_lines_are_numbered_from_one(self):
        self.assertEqual(util.fileline(self.filename, 1), "int main(void) {\n")
        self.assertEqual(util.fileline(self.filename, 4), "}\n")

    def test_line_numbers_outside_the_file_give_nothing(self):
        self.assertEqual(util.fileline(self.filename, 0), "")
        self.assertEqual(util.fileline(self.filename, -1), "")
        self.assertEqual(util.fileline(self.filename, 5), "")
        self.assertEqual(util.fileline(os.path.join(self.temp_dir.name, "missing.c"), 1), "")

    def test_surrounding_source_marks_the_error_line(self):
        lines = util.Location(self.filename, 3).surrounding_source(no_color, markMiddle=True)
        expected = ["int main(void) {\n", "    int a[10] = {0};\n", "--> return a[10];\n", "}\n"]
        self.assertEqual(lines, expected)

    def test_error_on_line_1_does_not_show_the_end_of_the_file(self):
        self.write_source("int main(void) { int a[1]; return a[1]; }\n    // trailing comment\n")
        lines = util.Location(self.filename, 1).surrounding_source(no_color, markMiddle=True)
        self.assertEqual(lines, ["-->int main(void) { int a[1]; return a[1]; }\n", "    // trailing comment\n"])

    def test_one_line_program_still_has_source_for_variables(self):
        self.write_source("int main(void) { int a[1]; return a[1]; }\n")
        lines = util.Location(self.filename, 1).surrounding_source(no_color, clean=True)
        self.assertEqual(lines, ["int main(void) { int a[1]; return a[1]; }\n"])


class CompilerMessageParsingTests(unittest.TestCase):
    """get_next_message splits compiler output into messages"""

    CLANG_OUTPUT = (
        "prog.c:4:11: warning: format specifies type 'int *' but the argument has type 'int' [-Wformat]\n"
        '    scanf("%d", i);\n'
        "           ~~   ^\n"
        "prog.c:9:5: error: use of undeclared identifier 'count'\n"
        "    count++;\n"
        "    ^\n"
        "1 warning and 1 error generated.\n"
    )

    def test_messages_are_split_and_parsed(self):
        lines = self.CLANG_OUTPUT.splitlines()
        message, lines = explain_compiler_output.get_next_message(lines)
        self.assertEqual((message.file, message.line_number, message.column, message.type), ("prog.c", "4", "11", "warning"))
        self.assertEqual(message.highlighted_word, "i")
        self.assertEqual(message.underlined_word, "%d")
        message, lines = explain_compiler_output.get_next_message(lines)
        self.assertEqual((message.line_number, message.type, message.highlighted_word), ("9", "error", "count"))
        self.assertEqual(lines, [])

    def test_notes_are_kept_separately(self):
        output = (
            "prog.c:3:5: error: call to undeclared function 'f'\n"
            "    f();\n"
            "    ^\n"
            "prog.c:1:6: note: 'g' declared here\n"
            "void g(void);\n"
            "     ^\n"
        )
        message, lines = explain_compiler_output.get_next_message(output.splitlines())
        self.assertEqual(message.text, output.splitlines()[:3])
        self.assertEqual(message.note, output.splitlines()[3:])
        self.assertEqual(lines, [])


class CompilerOutputTests(unittest.TestCase):
    """explain_compiler_output prints the compiler's messages with explanations"""

    class Args:  # the options explain_compiler_output uses
        colorize_output = False
        debug = 0
        max_explanations = 3
        compile_helper = ""

    def output_for(self, compiler_output):
        stderr = io.StringIO()
        with contextlib.redirect_stderr(stderr):
            explain_compiler_output.explain_compiler_output(compiler_output, self.Args())
        return stderr.getvalue()

    def test_no_escape_codes_without_colour(self):
        with_note = (
            "prog.c:3:5: warning: variable 'x' is uninitialized when used here [-Wuninitialized]\n"
            "    return x;\n"
            "           ^\n"
            "prog.c:2:10: note: initialize the variable 'x' to silence this warning\n"
            "    int x;\n"
            "         ^\n"
            "          = 0\n"
            "1 warning generated.\n"
        )
        gcc_quotes = "prog.c:3:13: warning: ‘a’ is used uninitialized [-Wuninitialized]\n    3 |     return a[0];\n"
        for compiler_output in [with_note, gcc_quotes]:
            output = self.output_for(compiler_output)
            self.assertIn("dcc explanation:", output)
            self.assertNotIn("\x1b", output)

    def test_a_repeated_include_chain_is_collapsed(self):
        # a cyclic #include makes the compiler repeat the chain ~100 times
        chain = (
            "In file included from prog.c:1:\nIn file included from ./prog.h:1:\n" * 100
        )
        output = self.output_for(
            chain + "./prog.h:1:10: error: #include nested too deeply\n"
        )
        self.assertEqual(output.count("In file included from"), 2)
        self.assertIn("# previous 2 lines repeated 99 more times", output)
        self.assertIn("#include nested too deeply", output)

    def test_an_unrepeated_include_chain_is_left_alone(self):
        chain = (
            "In file included from prog.c:1:\n"
            "In file included from ./a.h:1:\n"
            "In file included from ./b.h:1:\n"
        )
        output = self.output_for(
            chain + "./c.h:1:22: error: use of undeclared identifier 'x'\n"
        )
        self.assertEqual(output.count("In file included from"), 3)
        self.assertNotIn("# previous", output)

    def test_a_system_header_note_after_an_include_chain_is_not_printed(self):
        # the chain line leaves the note leading its own message
        output = self.output_for(
            "prog.c:5:5: warning: argument 1 null where non-null expected [-Wnonnull]\n"
            "    5 |     fgetc(f);\n"
            "      |     ^~~~~~~~\n"
            "In file included from prog.c:1:\n"
            "/usr/include/stdio.h:575:12: note: in a call to function 'fgetc'"
            " declared 'nonnull'\n"
            "  575 | extern int fgetc (FILE *__stream) __nonnull ((1));\n"
            "      |            ^~~~~\n"
        )
        self.assertIn("In file included from prog.c:1:", output)
        self.assertNotIn("/usr/include/stdio.h", output)
        self.assertNotIn("__nonnull", output)


class RuntimeExplanationTests(unittest.TestCase):
    """explanations of signals"""

    def test_stack_overflow_and_abort(self):
        import signal as signals  # pylint: disable=import-outside-toplevel

        with mock.patch.dict(os.environ, {"DCC_STACK_OVERFLOW": "1"}):
            self.assertIn("infinite recursion", explain_error.explain_signal(signals.SIGSEGV))
        with mock.patch.dict(os.environ, {}, clear=False):
            os.environ.pop("DCC_STACK_OVERFLOW", None)
            self.assertIn("invalid pointer", explain_error.explain_signal(signals.SIGSEGV))
        # abort() is only blamed on assert() when assert() really did call it
        assert_stack = "#15 0x7f in __assert_fail_base () at ./assert/assert.c:118"
        self.assertIn("assert", explain_error.explain_signal(signals.SIGABRT, assert_stack))
        throw_stack = "#14 0x7f in __cxa_throw () from /lib/libstdc++.so.6"
        abort_explanation = explain_error.explain_signal(signals.SIGABRT, throw_stack)
        self.assertIn("exception", abort_explanation)
        self.assertNotIn("assert", abort_explanation)
        self.assertNotIn("assert", explain_error.explain_signal(signals.SIGABRT))

    def test_debug_level_from_environment(self):
        with mock.patch.dict(os.environ, {"DCC_DEBUG": "2"}):
            self.assertEqual(util.debug_level_from_environment(), 2)
        with mock.patch.dict(os.environ, {"DCC_DEBUG": "yes"}):
            self.assertEqual(util.debug_level_from_environment(), 0)


class ExplanationTests(unittest.TestCase):
    """explanations are selected by matching the compiler message"""

    @staticmethod
    def explanation_for(compiler_output):
        message, _ = explain_compiler_output.get_next_message(compiler_output.splitlines())
        return compiler_explanations.get_explanation(message, colorize_output=False)

    def test_undeclared_identifier(self):
        e = self.explanation_for("prog.c:9:5: error: use of undeclared identifier 'count'\n    count++;\n    ^\n")
        self.assertIn("'count'", e.text)
        self.assertIn("without previously declaring it", e.text)

    def test_scanf_missing_ampersand(self):
        e = self.explanation_for(CompilerMessageParsingTests.CLANG_OUTPUT)
        self.assertEqual(e.label, "scanf_missing_ampersand")
        self.assertIn("forgotten an '&' before 'i'", e.text)

    def test_gcc_uninitialized_variable_wording(self):
        # gcc uses smart quotes and dropped "in this function" from the message in gcc 10
        e = self.explanation_for("prog.c:3:13: warning: ‘a’ is used uninitialized [-Wuninitialized]\n    3 |     return a[0];\n")
        self.assertEqual(e.label, "uninitialized-local-variable")

    def test_colours_are_used_only_when_asked_for(self):
        # a helper script is given the explanation as plain text
        message, _ = explain_compiler_output.get_next_message(
            "prog.c:9:5: error: use of undeclared identifier 'count'\n    count++;\n    ^\n".splitlines()
        )
        self.assertNotIn("\x1b", compiler_explanations.get_explanation(message, colorize_output=False).text)
        self.assertIn("\x1b", compiler_explanations.get_explanation(message, colorize_output=True).text)

    def test_unknown_message_has_no_explanation(self):
        self.assertIsNone(self.explanation_for("prog.c:1:1: error: something dcc has never heard of\n"))

    def test_labels_are_unique(self):
        # labels name the files of the extracted compile-time tests
        labels = [e.label for e in compiler_explanations.explanations]
        duplicates = sorted({label for label in labels if labels.count(label) > 1})
        self.assertEqual(duplicates, [])

    def test_every_explanation_has_a_reproduce_program(self):
        missing = [e.label for e in compiler_explanations.explanations if not e.reproduce.strip()]
        self.assertEqual(missing, [])


class OptionsTests(unittest.TestCase):
    """dcc's own command line options and the clang options it inspects"""

    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.old_cwd = os.getcwd()
        os.chdir(self.temp_dir.name)
        with open("prog.c", "w", encoding="utf-8") as f:
            f.write("int main(void) { return 0; }\n")

    def tearDown(self):
        os.chdir(self.old_cwd)
        self.temp_dir.cleanup()

    @staticmethod
    def parse(*args):
        with contextlib.redirect_stderr(io.StringIO()):
            parsed = options.parse_args(list(args))
        parsed.tar.close()
        return parsed

    def test_source_files_and_defaults(self):
        parsed = self.parse("prog.c")
        self.assertEqual(parsed.source_files, {"prog.c"})
        self.assertEqual(parsed.object_pathname, "a.out")
        self.assertFalse(parsed.libraries_being_linked)

    def test_sanitizer_selection(self):
        self.assertEqual(self.parse("-fsanitize=address,valgrind", "prog.c").sanitizers, ["address", "valgrind"])
        with self.assertRaises(SystemExit):
            self.parse("-fsanitize=bogus", "prog.c")

    def test_libraries_other_than_libc_and_libm_are_noticed(self):
        self.assertFalse(self.parse("-lm", "prog.c").libraries_being_linked)
        self.assertTrue(self.parse("-lcurl", "prog.c").libraries_being_linked)
        separated = self.parse("-l", "curl", "prog.c")
        self.assertTrue(separated.libraries_being_linked)
        self.assertEqual(separated.user_supplied_compiler_args[:2], ["-l", "curl"])
        with self.assertRaises(SystemExit):
            self.parse("prog.c", "-l")

    def test_pthreads_is_rewritten_for_gcc(self):
        parsed = self.parse("-pthreads", "prog.c")
        self.assertTrue(parsed.threads_used)
        self.assertIn("-pthread", parsed.user_supplied_compiler_args)
        self.assertNotIn("-pthreads", parsed.user_supplied_compiler_args)

    def test_response_files(self):
        with open("args.rsp", "w", encoding="utf-8") as f:
            f.write('-Wextra "-DGREETING=\\"hi there\\""\nprog.c\n')
        parsed = self.parse("@args.rsp")
        self.assertEqual(parsed.user_supplied_compiler_args, ["-Wextra", '-DGREETING="hi there"', "prog.c"])
        with self.assertRaises(SystemExit):
            self.parse("@missing.rsp")
        with open("bad.rsp", "w", encoding="utf-8") as f:
            f.write('"unbalanced\n')
        with self.assertRaises(SystemExit):
            self.parse("@bad.rsp")

    def test_will_not_overwrite_source_with_executable(self):
        with self.assertRaises(SystemExit):
            self.parse("prog.c", "-o", "prog.c")

    def test_embedded_environment_variable(self):
        parsed = self.parse("--embedded_environment_variable=X=a=b", "prog.c")
        self.assertEqual(parsed.embedded_environment_variables, [("X", "a=b")])


class OutputDifferenceTests(unittest.TestCase):
    """explanations of incorrect output, from the values the C code puts in the environment"""

    @staticmethod
    def explanation(**variables):
        environment = {
            "DCC_EXPECTED_STDOUT": "",
            "DCC_OUTPUT_ERROR": "incorrect output",
            "DCC_ACTUAL_LINE_NUMBER": "1",
            "DCC_N_EXPECTED_BYTES_SEEN": "0",
            "DCC_N_ACTUAL_BYTES_SEEN": "0",
            "DCC_EXPECTED_LINE": "",
            "DCC_ACTUAL_LINE": "",
            "DCC_EXPECTED_COLUMN": "0",
            "DCC_ACTUAL_COLUMN": "0",
        }
        environment.update(variables)
        with mock.patch.dict(os.environ, environment):
            return explain_output_difference.explain_output_difference(no_color)

    def test_too_much_output_reports_a_bound(self):
        text = self.explanation(DCC_OUTPUT_ERROR="too much output", DCC_N_ACTUAL_BYTES_SEEN="95", DCC_ACTUAL_COLUMN="6", DCC_ACTUAL_LINE="line 1")
        self.assertIn("too much output", text)
        self.assertIn("more than 101 bytes", text)

    def test_extra_characters_at_end_of_last_line(self):
        text = self.explanation(DCC_EXPECTED_STDOUT="Hello", DCC_EXPECTED_LINE="Hello", DCC_ACTUAL_LINE="Hello!", DCC_EXPECTED_COLUMN="5", DCC_ACTUAL_COLUMN="5")
        self.assertIn("extra characters at the end of the line", text)
        self.assertNotIn("more characters were expected", text)

    def test_missing_final_newline(self):
        text = self.explanation(DCC_EXPECTED_STDOUT="Hello\n", DCC_EXPECTED_LINE="Hello\n", DCC_ACTUAL_LINE="Hello", DCC_EXPECTED_COLUMN="5", DCC_ACTUAL_COLUMN="5")
        self.assertIn("newline was missing", text)

    def test_missing_last_character(self):
        text = self.explanation(DCC_EXPECTED_STDOUT="Hello!\n", DCC_EXPECTED_LINE="Hello!\n", DCC_ACTUAL_LINE="Hello\n", DCC_EXPECTED_COLUMN="5", DCC_ACTUAL_COLUMN="5")
        self.assertIn("'!' was missing from the end of the output line", text)

    def test_no_output(self):
        text = self.explanation(DCC_EXPECTED_STDOUT="Hello\n", DCC_EXPECTED_LINE="Hello\n")
