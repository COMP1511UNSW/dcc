class TracebackTests(unittest.TestCase):
    """the function call traceback shows the innermost calls and main"""

    @staticmethod
    def frames(n_frames):
        # the innermost n_frames - 1 calls are to f, the outermost is main
        stack = [
            util.Location("prog.c", 10 + i, function="f", params=f"n={i}", frame_number=str(i))
            for i in range(n_frames - 1)
        ]
        return stack + [util.Location("prog.c", 99, function="main", params="", frame_number=str(n_frames - 1))]

    def traceback(self, n_frames, truncated=False):
        return explain_context.explain_stack(self.frames(n_frames), [], no_color, truncated=truncated).splitlines()

    def test_every_call_shown_has_its_call_site(self):
        for n_frames in [2, 3, 10, 11, 12, 13, 50]:
            lines = self.traceback(n_frames)
            for line in lines[:-1]:
                if line != "...":
                    self.assertIn(" called at line ", line, f"{n_frames} frames: {line}")
            self.assertEqual(lines[-1], "main()", f"{n_frames} frames")

    def test_short_stacks_are_shown_in_full(self):
        for n_frames in [1, 2, 10, 11]:
            self.assertEqual(len(self.traceback(n_frames)), n_frames)
            self.assertNotIn("...", self.traceback(n_frames))

    def test_long_stacks_are_shortened_but_keep_main(self):
        lines = self.traceback(50)
        self.assertEqual(len(lines), explain_context.MAX_CALLS_SHOWN + 2)
        self.assertEqual(lines[explain_context.MAX_CALLS_SHOWN], "...")
        self.assertEqual(lines[-1], "main()")

    def test_a_truncated_stack_does_not_pretend_to_show_main(self):
        lines = self.traceback(50, truncated=True)
        self.assertEqual(lines[-1], "...")
        self.assertNotIn("main()", lines)
        self.assertEqual(len(lines), explain_context.MAX_CALLS_SHOWN + 1)

    def test_calls_are_selected_innermost_first_and_in_range(self):
        # get_variable_addresses drives gdb to exactly these frames,
        # so they must be real frames and in the order the traceback shows
        for n_frames, truncated in [(1, False), (3, False), (12, False), (50, False), (5, True), (50, True)]:
            shown = explain_context.shown_calls(n_frames, truncated)
            indexes = [index for index in shown if index is not None]
            self.assertEqual(indexes, sorted(indexes), f"{n_frames} {truncated}")
            self.assertEqual(indexes[0], 0, f"{n_frames} {truncated}")
            for index in indexes:
                self.assertLess(index, n_frames, f"{n_frames} {truncated}")
            self.assertLessEqual(shown.count(None), 1, f"{n_frames} {truncated}")


class StackParsingTests(unittest.TestCase):
    """gdb's backtrace lines are parsed into locations, ignoring library frames"""

    def test_user_frame(self):
        frame = explain_error.parse_gdb_stack_frame("#1  0x0000555555555189 in __real_main (argc=1, argv=0x7ffd) at prog.c:5")
        self.assertEqual((frame.function, frame.filename, frame.line_number, frame.frame_number), ("main", "prog.c", 5, "1"))

    def test_library_frames_are_ignored(self):
        for line in [
            "#0  __GI_raise (sig=6) at ../sysdeps/unix/sysv/linux/raise.c:50",
            "#2  0x00007ffff7 in __libc_start_main () at /usr/lib/libc.c:300",
            "#0  0x00007ffff7e2 in __strlen_avx2 () from /lib/x86_64-linux-gnu/libc.so.6",
            "#5  0x00007ffff7 in _IO_new_file_close_it (fp=0x51) at ./libio/libioP.h:1041",
            "#8  0x00005ed1d8 in _explain_error () at <stdin>:1685",
        ]:
            self.assertIsNone(explain_error.parse_gdb_stack_frame(line), line)

    def test_paths_with_spaces_and_underscored_functions(self):
        # a student's file may be called "assignment 1.c" and their function _f
        for line, expected in [
            ("#13 0x00005ed1d8 in main () at assignment 1.c:4", ("main", "assignment 1.c", 4)),
            ("#13 0x00005ed1d8 in main () at lab 3/prog.c:4", ("main", "lab 3/prog.c", 4)),
            ("#13 0x00005ed1d8 in main () at wei:rd.c:2", ("main", "wei:rd.c", 2)),
            ("#13 0x00005ed1d8 in _f () at min.c:1", ("_f", "min.c", 1)),
            ("#13 0x00005ed1d8 in __f (n=5) at dunder.c:4", ("__f", "dunder.c", 4)),
            ("#13 0x00005ed1d8 in _Deref (n=3) at dunder.c:3", ("_Deref", "dunder.c", 3)),
        ]:
            frame = explain_error.parse_gdb_stack_frame(line)
            self.assertIsNotNone(frame, line)
            self.assertEqual((frame.function, frame.filename, frame.line_number), expected)

    def test_a_stack_with_no_user_source_does_not_fall_back_to_a_library_frame(self):
        # exiting main runs the C library's _dl_call_fini, whose source dcc can
        # not see, so there is no frame it can usefully report
        stack = """#0  0x00007ffff7 in _dl_call_fini (closure_map=0x7ffff7) at ./elf/dl-call_fini.c:43
#1  0x00007ffff7 in _dl_fini () at ./elf/dl-fini.c:120
#2  0x00007ffff7 in __run_exit_handlers (status=0) at ./stdlib/exit.c:108"""
        with mock.patch.object(explain_error.gdb_interface, "gdb_execute", return_value=stack):
            with mock.patch.object(explain_error.gdb_interface, "gdb_set_frame"):
                frames, _, text = explain_error.parse_stack()
        self.assertEqual(frames, [])
        self.assertEqual(text, stack)


